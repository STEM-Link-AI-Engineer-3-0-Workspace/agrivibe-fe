def icon(name: str, size: int = 16, cls: str = "") -> str:
    """One icon as inline SVG, sized in px like shadcn's size-4 (16) or size-3.5 (14)."""
    css = f' class="{cls}"' if cls else ""
    return (
        f'<svg{css} width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{PATHS[name]}</svg>'
    )


def mask(name: str) -> str:
    """An icon as a CSS mask image, to draw one where there is no HTML to put an <svg> in."""
    svg = (
        "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='2' "
        f"stroke-linecap='round' stroke-linejoin='round'>{PATHS[name]}</svg>"
    ).replace('"', "'")
    return f'url("data:image/svg+xml,{quote(svg)}")'
